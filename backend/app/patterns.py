import re

PATTERNS = {

    # ---------------- EMAIL ----------------

    "EMAIL": re.compile(
        r"(?<![A-Za-z0-9._%+-])"
        r"[A-Za-z0-9_%+-]+"
        r"(?:\.[A-Za-z0-9_%+-]+)*"
        r"@"
        r"[A-Za-z0-9-]+"
        r"(?:\.[A-Za-z0-9-]+)*"
        r"\.[A-Za-z]{2,}"
        r"(?![A-Za-z0-9_-])"
    ),

    # ---------------- PHONE (INDIA) ----------------

    "PHONE": re.compile(
        r"(?<!\d)"
        r"(?:\+91[\s.-]?|91[\s.-]?|0)?"
        r"[6-9]\d{4}[\s.-]?\d{5}"
        r"(?!\d)"
    ),

    # ---------------- INDIAN PINCODE ----------------

    "PINCODE": re.compile(
        r"(?<!\d)"
        r"[1-9]\d{5}"
        r"(?!\d)"
    ),

    # ---------------- IPV4 ADDRESS ----------------

    "IP_ADDRESS": re.compile(
        r"(?<![\d.])"
        r"(?:\d{1,3}\.){3}\d{1,3}"
        r"(?![\d.])"
    ),
}